export function getToolUiTranslation(lang = 'en', key, params = {}) {
  const dict = TOOL_UI_DICTIONARY[lang] || TOOL_UI_DICTIONARY.en;
  let text = dict[key] || TOOL_UI_DICTIONARY.en[key] || key;
  Object.keys(params).forEach((p) => {
    text = text.replace(`{${p}}`, params[p]);
  });
  return text;
}
